#!/usr/bin/env python3
"""Generate a paper-explainer SFX list from a scene file's beat times.
    python3 scripts/paper_sfx.py src/paper/<Video>.tsx src/paper/<video>Sfx.ts [--ding 40.4,46.0 ...]
pop on <Pop>/<Label>/<ValueCard>, impact on <Stamp>, click on <XMark>, swell_hit on NumberCard/TakeawayCard,
whoosh on scene starts, ding on the given money moments. Priority-ordered, min gap 0.9 s (0.5 s for priority hits)."""
import re, sys, argparse
ap = argparse.ArgumentParser(); ap.add_argument('src'); ap.add_argument('out'); ap.add_argument('--ding', default='')
a = ap.parse_args(); s = open(a.src).read()
f = lambda pat: sorted({float(x) for x in re.findall(pat, s)})
ev = [(t, 'whoosh', 0.25, 1) for t in [float(x) for x in re.findall(r'\{from: ([\d.]+), to:', s)][1:]]
ev += [(t, 'swell_hit', 0.35, 3) for t in f(r'<(?:NumberCard|TakeawayCard)[^>]*?at=\{([\d.]+)\}')]
ev += [(t, 'impact', 0.4, 3) for t in f(r'<Stamp[^>]*?at=\{([\d.]+)\}')]
ev += [(float(t), 'ding', 0.3, 2) for t in a.ding.split(',') if t]
ev += [(t, 'click', 0.4, 2) for t in f(r'<XMark[^>]*?at=\{([\d.]+)\}')]
ev += [(t, 'pop', 0.32, 0) for t in f(r'<(?:Pop|Label|ValueCard)[^>]*?at=\{([\d.]+)\}')]
ev.sort(key=lambda e: (-e[3], e[0])); kept = []
for e in ev:
    if all(abs(e[0] - k[0]) >= (0.9 if e[3] < 2 else 0.5) for k in kept): kept.append(e)
kept.sort()
open(a.out, 'w').write("// generated by scripts/paper_sfx.py from beat times; do not edit by hand\nimport type {Sfx} from './kit';\nexport const SFX: Sfx[] = [\n" + ''.join(f"  [{t}, '{n}', {v}],\n" for t, n, v, _ in kept) + "];\n")
print(len(kept), 'sfx ->', a.out)
